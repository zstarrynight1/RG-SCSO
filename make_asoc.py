"""
make_asoc.py — derive the Applied Soft Computing (Elsevier/elsarticle) manuscript
from the authoritative IJCS source, guaranteeing content parity (no stale numbers).

The IJCS tex body is class-agnostic; only the front matter (sn-jnl -> elsarticle
frontmatter) and the bibliography style change. Run after regenerating the IJCS tex:
    python3 build_paper_ijcs.py   # authoritative content
    python3 make_asoc.py          # -> RG-SCSO_ASOC.tex, _Supplementary.tex, _Highlights.txt
"""
from __future__ import annotations

import re

IJCS_TEX = "RG-SCSO_IJCS.tex"
IJCS_SUPP = "RG-SCSO_IJCS_Supplementary.tex"
OUT_TEX = "RG-SCSO_ASOC.tex"
OUT_SUPP = "RG-SCSO_ASOC_Supplementary.tex"
OUT_HL = "RG-SCSO_ASOC_Highlights.txt"


def _balanced(src: str, start_token: str) -> str:
    """Return the balanced-brace content of e.g. \\abstract{...}."""
    i = src.index(start_token) + len(start_token)
    assert src[i - 1] == "{"
    depth, j = 1, i
    while depth:
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
        j += 1
    return src[i : j - 1]


def build() -> None:
    tex = open(IJCS_TEX).read()

    # --- front matter extraction ---------------------------------------
    title = _balanced(tex, "\\title[RG-SCSO for Parsimonious Feature Selection]{")
    title = re.sub(r"\s+", " ", title).strip()
    abstract = _balanced(tex, "\\abstract{").strip()
    keywords_raw = _balanced(tex, "\\keywords{")
    keywords = [k.strip() for k in re.sub(r"\s+", " ", keywords_raw).split(",") if k.strip()]

    # --- body: from after \maketitle to before \bibliography ----------
    body = tex[tex.index("\\maketitle") + len("\\maketitle") : tex.index("\\bibliography{references}")]
    body = body.strip("\n")

    preamble = r"""% !TeX program = pdflatex
%=======================================================================
% RG-SCSO, Elsevier (elsarticle) format, target: Applied Soft Computing.
% Generated by make_asoc.py from the authoritative RG-SCSO_IJCS.tex body
% (identical content; only the class/frontmatter/bibliography differ).
%=======================================================================
\documentclass[preprint,3p,times]{elsarticle}
\usepackage{amsmath}
\usepackage{amssymb}
\usepackage{amsthm}
\usepackage{algorithm}
\usepackage{algorithmic}
\usepackage{graphicx}
\graphicspath{{figures/}{./}}
\usepackage{booktabs}
\usepackage{multirow}
\usepackage{rotating}
\usepackage{url}
\usepackage{placeins}

% Reduce float-induced whitespace: let floats fill more of the page before a
% text page is forced, and tighten the gaps around them.
\renewcommand{\topfraction}{0.9}
\renewcommand{\bottomfraction}{0.85}
\renewcommand{\textfraction}{0.08}
\renewcommand{\floatpagefraction}{0.75}
\setcounter{topnumber}{3}
\setcounter{bottomnumber}{2}
\setcounter{totalnumber}{5}
\setlength{\textfloatsep}{12pt plus 2pt minus 2pt}
\setlength{\floatsep}{10pt plus 2pt minus 2pt}

\newtheorem{lemma}{Lemma}
\newtheorem{proposition}[lemma]{Proposition}

\journal{Applied Soft Computing}

\begin{document}

\begin{frontmatter}

\title{__TITLE__}

\author[1]{Bui Quang Huy}
\ead{huybq@donga.edu.vn}
\author[1]{Duong Minh Son}
\ead{sondm@donga.edu.vn}
\affiliation[1]{organization={Dong A University}, city={Da Nang}, country={Vietnam}}

\begin{abstract}
__ABSTRACT__
\end{abstract}

\begin{graphicalabstract}
\centering
\includegraphics[width=0.34\textwidth]{graphical_abstract.pdf}
\end{graphicalabstract}

\begin{highlights}
__HIGHLIGHTS__
\end{highlights}

\begin{keyword}
__KEYWORDS__
\end{keyword}

\end{frontmatter}
"""
    highlights = [
        "Transfer-function binarization discards swarm search detail; we name it washout",
        "RG-SCSO injects per-feature MI relevance into the binarization decision of SCSO",
        "Best mean accuracy and second-smallest subsets across 18 datasets at equal budget",
        "Ablation localizes the gain to the binarization step, not init or the objective",
        "Leak-free gain holds across KNN/SVM/RF wrappers; bounded on p>>n gene-expression",
    ]
    for h in highlights:
        if len(h) > 85:
            raise ValueError(f"Highlight too long ({len(h)}): {h}")
    highlights_tex = "\n".join(f"\\item {h}" for h in highlights)
    preamble = (preamble.replace("__TITLE__", title)
                        .replace("__ABSTRACT__", abstract)
                        .replace("__HIGHLIGHTS__", highlights_tex)
                        .replace("__KEYWORDS__", " \\sep ".join(keywords)))

    backmatter = r"""
\bibliographystyle{elsarticle-num}
\bibliography{references}

\end{document}
"""

    with open(OUT_TEX, "w") as fh:
        fh.write(preamble + "\n" + body + "\n" + backmatter)

    # --- supplementary: reuse IJCS supplementary (article class, journal-agnostic) ---
    supp = open(IJCS_SUPP).read()
    supp = supp.replace(
        "Supplementary Information for: Relevance-Guided",
        "Supplementary Information (Applied Soft Computing) for: Relevance-Guided",
    )
    with open(OUT_SUPP, "w") as fh:
        fh.write(supp)

    # --- Highlights (Elsevier: 3-5 bullets, <= 85 chars each) ----------
    highlights = [
        "Transfer-function binarization discards swarm search detail; we name it washout",
        "RG-SCSO injects per-feature MI relevance into the binarization decision of SCSO",
        "Best mean accuracy and second-smallest subsets across 18 datasets at equal budget",
        "Ablation localizes the gain to the binarization step, not init or the objective",
        "Leak-free gain holds across KNN/SVM/RF wrappers; bounded on p>>n gene-expression",
    ]
    for h in highlights:
        if len(h) > 85:
            raise ValueError(f"Highlight too long ({len(h)}): {h}")
    with open(OUT_HL, "w") as fh:
        fh.write("\n".join(highlights) + "\n")

    print(f"Wrote {OUT_TEX}, {OUT_SUPP}, {OUT_HL}")
    print(f"  title chars={len(title)}  abstract words={len(abstract.split())}  "
          f"keywords={len(keywords)}  highlights={len(highlights)} (max {max(len(h) for h in highlights)} chars)")


if __name__ == "__main__":
    build()
